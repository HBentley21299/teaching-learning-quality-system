public sealed record GeneratedExport(byte[] Content, string ContentType, string FileName);

public sealed class ExcelExportService
{
    public GeneratedExport CreateWorkbook(ExportWorkbookData data)
    {
        using var stream = new MemoryStream();
        using (var document = SpreadsheetDocument.Create(stream, SpreadsheetDocumentType.Workbook, true))
        {
            var workbookPart = document.AddWorkbookPart();
            workbookPart.Workbook = new S.Workbook();
            var styles = workbookPart.AddNewPart<WorkbookStylesPart>();
            styles.Stylesheet = CreateStylesheet();
            styles.Stylesheet.Save();
            var sheets = workbookPart.Workbook.AppendChild(new S.Sheets());
            uint sheetId = 1;

            AddSheet(workbookPart, sheets, CreateInformationSheet(data), sheetId++);
            foreach (var sheet in data.Sheets)
                AddSheet(workbookPart, sheets, sheet, sheetId++);
            workbookPart.Workbook.Save();
        }
        return new GeneratedExport(
            stream.ToArray(),
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            $"{SafeFileName(data.ModuleKey)}-{data.GeneratedAt:yyyy-MM-dd}.xlsx");
    }

    private static ExportSheet CreateInformationSheet(ExportWorkbookData data)
    {
        var rows = new List<IReadOnlyList<string?>>
        {
            new string?[] { "Export area", data.DisplayName },
            new string?[] { "Generated by", data.GeneratedBy },
            new string?[] { "Generated at", data.GeneratedAt.ToString("dd MMM yyyy HH:mm 'UTC'") },
            new string?[] { "Academic year", data.Filter.AcademicYear },
            new string?[] { "Faculty", data.Filter.FacultyCode },
            new string?[] { "Sub-team", data.Filter.TeamCode },
            new string?[] { "From date", data.Filter.FromDate?.ToString("dd MMM yyyy") },
            new string?[] { "To date", data.Filter.ToDate?.ToString("dd MMM yyyy") },
            new string?[] { "Status", data.Filter.Status },
            new string?[] { "Interactive row limit", SqlFoundationDataStore.InteractiveExportRowLimit.ToString() }
        };
        foreach (var sheet in data.Sheets.Where(item => item.WasTruncated))
            rows.Add(new string?[] { $"{sheet.Name} warning", $"Results were limited to {SqlFoundationDataStore.InteractiveExportRowLimit:N0} rows. Narrow the filters and export again." });
        return new ExportSheet("Export Information", ["Property", "Value"], rows, false);
    }

    private static void AddSheet(
        WorkbookPart workbookPart,
        S.Sheets sheets,
        ExportSheet data,
        uint sheetId)
    {
        var worksheetPart = workbookPart.AddNewPart<WorksheetPart>();
        using (var writer = OpenXmlWriter.Create(worksheetPart))
        {
            writer.WriteStartElement(new S.Worksheet());
            writer.WriteElement(new S.SheetViews(
                new S.SheetView(
                    new S.Pane
                    {
                        VerticalSplit = 1D,
                        TopLeftCell = "A2",
                        ActivePane = S.PaneValues.BottomLeft,
                        State = S.PaneStateValues.Frozen
                    })
                { WorkbookViewId = 0U }));
            var columns = new S.Columns();
            for (uint index = 1; index <= data.Columns.Count; index++)
                columns.Append(new S.Column { Min = index, Max = index, Width = index == 1 ? 24D : 20D, CustomWidth = true });
            writer.WriteElement(columns);
            writer.WriteStartElement(new S.SheetData());
            WriteRow(writer, data.Columns.Cast<string?>(), 1U);
            foreach (var row in data.Rows) WriteRow(writer, row, 0U);
            writer.WriteEndElement();
            if (data.Columns.Count > 0)
            {
                writer.WriteElement(new S.AutoFilter
                {
                    Reference = $"A1:{ColumnName(data.Columns.Count)}{data.Rows.Count + 1}"
                });
            }
            writer.WriteEndElement();
        }
        sheets.Append(new S.Sheet
        {
            Id = workbookPart.GetIdOfPart(worksheetPart),
            SheetId = sheetId,
            Name = data.Name
        });
    }

    private static void WriteRow(OpenXmlWriter writer, IEnumerable<string?> values, uint styleIndex)
    {
        writer.WriteStartElement(new S.Row());
        foreach (var value in values)
        {
            var clean = CleanCellText(value);
            writer.WriteElement(new S.Cell
            {
                DataType = S.CellValues.InlineString,
                StyleIndex = styleIndex,
                InlineString = new S.InlineString(new S.Text(clean) { Space = SpaceProcessingModeValues.Preserve })
            });
        }
        writer.WriteEndElement();
    }

    private static S.Stylesheet CreateStylesheet() => new(
        new S.Fonts(
            new S.Font(new S.FontName { Val = "Aptos" }, new S.FontSize { Val = 10D }),
            new S.Font(new S.Bold(), new S.Color { Rgb = "FFFFFFFF" }, new S.FontName { Val = "Aptos" }, new S.FontSize { Val = 10D })),
        new S.Fills(
            new S.Fill(new S.PatternFill { PatternType = S.PatternValues.None }),
            new S.Fill(new S.PatternFill { PatternType = S.PatternValues.Gray125 }),
            new S.Fill(new S.PatternFill(new S.ForegroundColor { Rgb = "FF087F6F" }) { PatternType = S.PatternValues.Solid })),
        new S.Borders(new S.Border()),
        new S.CellStyleFormats(new S.CellFormat()),
        new S.CellFormats(
            new S.CellFormat { FontId = 0U, FillId = 0U, BorderId = 0U },
            new S.CellFormat { FontId = 1U, FillId = 2U, BorderId = 0U, ApplyFont = true, ApplyFill = true,
                Alignment = new S.Alignment { WrapText = true, Vertical = S.VerticalAlignmentValues.Center } }),
        new S.CellStyles(new S.CellStyle { Name = "Normal", FormatId = 0U, BuiltinId = 0U }));

    private static string ColumnName(int number)
    {
        var name = "";
        while (number > 0)
        {
            number--;
            name = (char)('A' + number % 26) + name;
            number /= 26;
        }
        return name;
    }

    private static string CleanCellText(string? value)
    {
        if (string.IsNullOrEmpty(value)) return "";
        var clean = string.Concat(value.Where(character => character is '\t' or '\n' or '\r' || character >= ' '));
        return clean[..Math.Min(clean.Length, 32_767)];
    }

    private static string SafeFileName(string value) =>
        Regex.Replace(value.ToLowerInvariant(), "[^a-z0-9-]+", "-").Trim('-');
}

