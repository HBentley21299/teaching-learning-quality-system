public sealed class WordExportService(Microsoft.Extensions.Options.IOptions<ExportBrandingOptions> configuredBranding)
{
    private readonly ExportBrandingOptions _branding = configuredBranding.Value;

    public GeneratedExport CreateRecordReport(RecordReportData data)
    {
        using var stream = new MemoryStream();
        using (var document = WordprocessingDocument.Create(stream, WordprocessingDocumentType.Document, true))
        {
            var main = document.AddMainDocumentPart();
            main.Document = new W.Document(new W.Body());
            AddStyles(main);
            AddHeader(main);
            AddFooter(main);
            var body = main.Document.Body!;
            body.Append(Heading(data.Title, 1));
            body.Append(Paragraph($"{Humanize(data.RecordType)} · {data.Status}", "Subtitle"));
            body.Append(DetailsTable([
                ("Staff member", data.StaffName),
                ("Reviewer", data.ReviewerName),
                ("Organisation", data.Organisation),
                ("Record date", data.RecordDate?.ToString("dd MMM yyyy")),
                ("Created by", data.CreatedBy),
                ("Created at", data.CreatedAt.ToString("dd MMM yyyy HH:mm")),
                ("Record ID", data.RecordId.ToString())
            ]));

            foreach (var section in data.Sections)
            {
                var populated = section.Fields.Where(field => !string.IsNullOrWhiteSpace(field.Value)).ToArray();
                if (populated.Length == 0) continue;
                body.Append(Heading(section.Title, 2));
                foreach (var field in populated)
                {
                    body.Append(Paragraph(field.Label, "FieldLabel"));
                    body.Append(Paragraph(field.Value!, "Normal"));
                }
            }

            if (data.Actions.Count > 0)
            {
                body.Append(Heading("Actions", 2));
                body.Append(ActionTable(data.Actions));
            }
            body.Append(new W.SectionProperties(
                new W.PageSize { Width = 11906U, Height = 16838U },
                new W.PageMargin { Top = 1080, Right = 1080U, Bottom = 1080, Left = 1080U, Header = 500U, Footer = 500U }));
            main.Document.Save();
        }
        return new GeneratedExport(
            stream.ToArray(),
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            $"{SafeFileName(data.Title)}-{data.RecordDate?.ToString("yyyy-MM-dd") ?? DateTime.UtcNow.ToString("yyyy-MM-dd")}.docx");
    }

    private void AddHeader(MainDocumentPart main)
    {
        var part = main.AddNewPart<HeaderPart>();
        part.Header = new W.Header(
            new W.Paragraph(
                new W.ParagraphProperties(new W.ParagraphStyleId { Val = "Header" }),
                new W.Run(new W.Text(_branding.ProductName)),
                new W.Run(new W.TabChar()),
                new W.Run(new W.Text(_branding.OrganisationName))));
        part.Header.Save();
        main.Document.Body!.Append(new W.SectionProperties(
            new W.HeaderReference { Type = W.HeaderFooterValues.Default, Id = main.GetIdOfPart(part) }));
    }

    private void AddFooter(MainDocumentPart main)
    {
        var part = main.AddNewPart<FooterPart>();
        part.Footer = new W.Footer(
            new W.Paragraph(
                new W.ParagraphProperties(new W.ParagraphStyleId { Val = "Footer" }),
                new W.Run(new W.Text(_branding.FooterText))));
        part.Footer.Save();
        var properties = main.Document.Body!.Elements<W.SectionProperties>().First();
        properties.Append(new W.FooterReference { Type = W.HeaderFooterValues.Default, Id = main.GetIdOfPart(part) });
    }

    private static void AddStyles(MainDocumentPart main)
    {
        var part = main.AddNewPart<StyleDefinitionsPart>();
        part.Styles = new W.Styles(
            Style("Normal", "Normal", 20, "1F2A27"),
            Style("Title", "Title", 36, "153F35", true),
            Style("Heading1", "Heading 1", 32, "153F35", true, 1),
            Style("Heading2", "Heading 2", 25, "087F6F", true, 2),
            Style("Subtitle", "Subtitle", 20, "62706A"),
            Style("FieldLabel", "Field label", 19, "31423C", true),
            Style("Header", "Header", 18, "087F6F", true),
            Style("Footer", "Footer", 16, "62706A"));
        part.Styles.Save();
    }

    private static W.Style Style(string id, string name, int halfPoints, string colour, bool bold = false, int? outline = null)
    {
        var paragraph = new W.ParagraphProperties(new W.SpacingBetweenLines { After = id == "Normal" ? "120" : "180" });
        if (outline.HasValue) paragraph.Append(new W.OutlineLevel { Val = outline.Value - 1 });
        var run = new W.RunProperties(new W.RunFonts { Ascii = "Aptos", HighAnsi = "Aptos" }, new W.FontSize { Val = halfPoints.ToString() }, new W.Color { Val = colour });
        if (bold) run.Append(new W.Bold());
        return new W.Style(paragraph, run)
        {
            Type = W.StyleValues.Paragraph,
            StyleId = id,
            CustomStyle = id is not ("Normal" or "Heading1" or "Heading2")
        }.WithName(name);
    }

    private static W.Paragraph Heading(string value, int level) => Paragraph(value, level == 1 ? "Heading1" : "Heading2");

    private static W.Paragraph Paragraph(string value, string style) => new(
        new W.ParagraphProperties(new W.ParagraphStyleId { Val = style }),
        new W.Run(new W.Text(value) { Space = SpaceProcessingModeValues.Preserve }));

    private static W.Table DetailsTable(IEnumerable<(string Label, string? Value)> values)
    {
        var table = BasicTable();
        foreach (var (label, value) in values.Where(item => !string.IsNullOrWhiteSpace(item.Value)))
            table.Append(new W.TableRow(Cell(label, true), Cell(value!)));
        return table;
    }

    private static W.Table ActionTable(IReadOnlyList<RecordReportAction> actions)
    {
        var table = BasicTable();
        table.Append(new W.TableRow(Cell("Action", true), Cell("Owner", true), Cell("Due date", true), Cell("Status", true)));
        foreach (var action in actions)
            table.Append(new W.TableRow(Cell(action.Action), Cell(action.Owner ?? ""), Cell(action.DueDate?.ToString("dd MMM yyyy") ?? ""), Cell(action.Status)));
        return table;
    }

    private static W.Table BasicTable() => new(
        new W.TableProperties(
            new W.TableWidth { Width = "5000", Type = W.TableWidthUnitValues.Pct },
            new W.TableBorders(
                new W.TopBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U },
                new W.BottomBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U },
                new W.LeftBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U },
                new W.RightBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U },
                new W.InsideHorizontalBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U },
                new W.InsideVerticalBorder { Val = W.BorderValues.Single, Color = "D8E0DA", Size = 4U })));

    private static W.TableCell Cell(string value, bool bold = false)
    {
        var run = new W.Run(new W.Text(value) { Space = SpaceProcessingModeValues.Preserve });
        if (bold) run.RunProperties = new W.RunProperties(new W.Bold());
        return new W.TableCell(new W.Paragraph(run), new W.TableCellProperties(new W.TableCellMargin(
            new W.TopMargin { Width = "80", Type = W.TableWidthUnitValues.Dxa },
            new W.BottomMargin { Width = "80", Type = W.TableWidthUnitValues.Dxa },
            new W.TableCellLeftMargin { Width = 100, Type = W.TableWidthValues.Dxa },
            new W.TableCellRightMargin { Width = 100, Type = W.TableWidthValues.Dxa })));
    }

    private static string Humanize(string value) => string.Join(' ', value.Split('_', '-', StringSplitOptions.RemoveEmptyEntries).Select(word => char.ToUpperInvariant(word[0]) + word[1..]));
    private static string SafeFileName(string value) => Regex.Replace(value.ToLowerInvariant(), "[^a-z0-9-]+", "-").Trim('-');
}

internal static class WordStyleExtensions
{
    public static W.Style WithName(this W.Style style, string name)
    {
        style.InsertAt(new W.StyleName { Val = name }, 0);
        return style;
    }
}
